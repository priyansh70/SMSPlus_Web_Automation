import { defineConfig, devices } from '@playwright/test';
import { configDotenv } from "dotenv";
import fs from "fs";
import path from "path";

const testEnvironment = (process.env.TEST_ENV ?? "local").toLowerCase();
const environmentFile =
  testEnvironment === "local" ? ".env" : `.env.${testEnvironment}`;
const environmentPath = path.resolve(environmentFile);

if (!fs.existsSync(environmentPath)) {
  throw new Error(
    `Environment file not found: ${environmentFile}. Use TEST_ENV=local, dev, staging, or production.`,
  );
}

configDotenv({ path: environmentPath });
// Keep shell variables and the local .env file as fallbacks.
configDotenv({ path: ".env", override: false });

